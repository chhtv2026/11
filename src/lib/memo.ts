// Памятка по участку: что можно, чего нельзя и при каких условиях — из трёх источников:
// ЗОУИТ по ЕГРН (проверка ограничений), водные полосы по закону (осмотр), генплан (слои ФГИС ТП).
// Нормы указаны по памяти о действующих редакциях — перед важным решением сверяйте с текстом закона.
import { waterKinds, waterStrips, type Survey } from "./water";

export type MemoSource = "ЕГРН" | "закон" | "генплан" | "осмотр";
export type MemoItem = { text: string; law: string; source: MemoSource; where?: string };
export type Memo = { forbidden: MemoItem[]; conditional: MemoItem[]; check: MemoItem[]; allowed: MemoItem[] };

type MemoInput = {
  restrictionZones: string[];
  restrictionsCheckedAt: string | null;
  planFindings: string[];
  planCheckedAt: string | null;
  survey: Survey;
};

const WATER_PROTECTION_BANS =
  "сточные воды для удобрения; кладбища, скотомогильники, отходы; авиаобработка ядохимикатами; хранение и применение пестицидов и агрохимикатов; движение и стоянка машин вне дорог (кроме специальной техники); АЗС и склады ГСМ; сброс дренажных вод; добыча песка и гравия";

export function buildMemo(p: MemoInput): Memo {
  const memo: Memo = { forbidden: [], conditional: [], check: [], allowed: [] };
  const zones = new Set(p.restrictionZones);

  // ЗОУИТ, ООПТ и лесничества по ЕГРН
  if (zones.has("forest")) {
    memo.forbidden.push({
      text: "Участок в основном в лесничестве (лесной фонд) — по ст. 10.1 101-ФЗ его не получить, сельхозработы на лесных землях не ведут.",
      law: "Лесной кодекс РФ; ст. 10.1 101-ФЗ",
      source: "ЕГРН",
    });
  }
  if (zones.has("forestEdge")) {
    memo.check.push({
      text: "Край участка заходит в лесничество — вероятна реестровая ошибка: граница участка не должна пересекать границу лесничества. Спросить администрацию, исправят ли границы до предоставления; до исправления часть участка юридически — лесной фонд.",
      law: "п. 7 ст. 11.9 ЗК РФ",
      source: "ЕГРН",
    });
  }
  if (zones.has("oopt")) {
    memo.check.push({
      text: "Участок (или часть) в ООПТ — что можно, решает положение о конкретной ООПТ: часто запрещены распашка новых земель, химия, строительство; сенокос и выпас бывают разрешены.",
      law: "33-ФЗ «Об особо охраняемых природных территориях»; положение об ООПТ",
      source: "ЕГРН",
    });
  }
  if (zones.has("heritage")) {
    memo.conditional.push({
      text: "Объект культурного наследия или его зона: земляные работы (вспашка глубже обычной, мелиорация, строительство) — только с обеспечением сохранности объекта, часто нужна историко-культурная экспертиза.",
      law: "ст. 34, 36 73-ФЗ «Об объектах культурного наследия»",
      source: "ЕГРН",
    });
  }
  if (zones.has("sanitary")) {
    memo.check.push({
      text: "Зона санитарной охраны водозабора: в I поясе любая хозяйственная деятельность запрещена; во II–III поясах ограничены удобрения, ядохимикаты, выпас и навоз. Уточнить пояс.",
      law: "ст. 43 ВК РФ; СанПиН 2.1.4.1110-02",
      source: "ЕГРН",
    });
  }
  if (zones.has("water")) {
    memo.forbidden.push({
      text: `Водоохранная зона (по ЕГРН): ${WATER_PROTECTION_BANS}.`,
      law: "ч. 15 ст. 65 ВК РФ",
      source: "ЕГРН",
    });
    memo.allowed.push({
      text: "В водоохранной зоне (вне прибрежной полосы) пахать, сеять, косить можно.",
      law: "ст. 65 ВК РФ",
      source: "ЕГРН",
    });
  }
  if (zones.has("utility")) {
    memo.conditional.push({
      text: "Охранная зона ЛЭП: без письменного согласия сетевой компании нельзя строить, копать глубже 0,3 м (на пашне — 0,45 м), работать машинами выше 4 м, складировать корма и удобрения, жечь. Пахать, сеять, косить обычной техникой можно.",
      law: "Правила, утв. ПП РФ от 24.02.2009 № 160, пп. 8–11",
      source: "ЕГРН",
    });
    memo.conditional.push({
      text: "Если это газопровод: нельзя строить и огораживать трассу, обрабатывать почву глубже 0,3 м без согласия газовой службы.",
      law: "Правила, утв. ПП РФ от 20.11.2000 № 878, п. 14",
      source: "ЕГРН",
    });
    memo.conditional.push({
      text: "Если это придорожная полоса: строить (в т. ч. ангар, навес) — только с согласия владельца дороги; ширина 25–75 м по категории дороги.",
      law: "ст. 26 257-ФЗ «Об автомобильных дорогах»",
      source: "ЕГРН",
    });
  }
  if (zones.has("flood")) {
    memo.forbidden.push({
      text: "Зона затопления/подтопления: нельзя удобрять сточными водами, размещать скотомогильники и отходы, авиаобработка ядохимикатами; строить — только с инженерной защитой. Для пашни терпимо, для построек КФХ — риск.",
      law: "ч. 3 ст. 67.1 ВК РФ",
      source: "ЕГРН",
    });
  }
  if (zones.has("other")) {
    memo.check.push({
      text: "Иная зона с особыми условиями — посмотреть её режим в карточке зоны или выписке; сельхозработам обычно не мешает.",
      law: "ст. 105 ЗК РФ",
      source: "ЕГРН",
    });
  }

  // Вода по закону — из осмотра (действует, даже если в ЕГРН зон нет)
  for (const w of p.survey.water) {
    const s = waterStrips(w);
    const name = `${waterKinds[w.kind]}${w.name.trim() ? ` ${w.name.trim()}` : ""}`;
    const where = w.distanceM === null ? name : `${name}, ${w.distanceM} м от участка`;
    const d = w.distanceM ?? Infinity;
    if (s.coastal !== null && d < s.coastal) {
      memo.forbidden.push({
        text: `Прибрежная защитная полоса (${s.coastal} м от воды, точнее 30–50 м по уклону берега): нельзя пахать, пасти скот и ставить летние лагеря и ванны, размещать отвалы грунта — плюс всё, что запрещено в водоохранной зоне. Косить можно.`,
        law: "ч. 11, 17 ст. 65 ВК РФ",
        source: "закон",
        where,
      });
    }
    if (s.protection !== null && d < s.protection) {
      memo.forbidden.push({
        text: `Водоохранная зона (${s.protection} м от воды): ${WATER_PROTECTION_BANS}.`,
        law: "ч. 4, 6, 15 ст. 65 ВК РФ",
        source: "закон",
        where,
      });
    }
    if (s.shore !== null && d < s.shore) {
      memo.conditional.push({
        text: `Береговая полоса (${s.shore} м от воды) — общего пользования: огораживать нельзя, проход к воде должен оставаться свободным.`,
        law: "ч. 6, 8 ст. 6 ВК РФ",
        source: "закон",
        where,
      });
    }
    if (s.touches === null) {
      memo.check.push({
        text: `Не хватает данных, чтобы посчитать полосы (${s.protectionNote}). Укажите расстояние и размер в осмотре.`,
        law: "ст. 65 ВК РФ",
        source: "осмотр",
        where: name,
      });
    }
  }
  if (p.survey.overgrown) {
    memo.check.push({
      text: "Участок зарастает лесом или кустарником: до работ — расчистка; рубку деревьев на сельхозземле оформляют по особому порядку. Неиспользование сельхозземли по назначению 3 года и более — основание для изъятия.",
      law: "ПП РФ от 21.09.2020 № 1509; ст. 6 101-ФЗ",
      source: "осмотр",
    });
  }
  if (p.survey.access === "none") {
    memo.check.push({
      text: "Подъезда не видно: проезд через чужую землю — по соглашению о сервитуте (или через суд); спросить администрацию о дороге.",
      law: "ст. 23 ЗК РФ; ст. 274 ГК РФ",
      source: "осмотр",
    });
  }

  // Генплан
  const plan = new Set(p.planFindings);
  if (plan.has("agri")) {
    memo.allowed.push({
      text: "По генплану — зона сельхозугодий: использование участка под сельхозпроизводство совпадает с планами муниципалитета.",
      law: "ст. 23 ГрК РФ (генплан)",
      source: "генплан",
    });
  }
  if (plan.has("forest") || plan.has("build")) {
    memo.check.push({
      text: `По генплану участок (или часть) — ${plan.has("forest") ? "зона лесов / рекреационная" : "зона застройки"}: муниципалитет видит его не сельхозугодьем. Спросить администрацию о планах: возможен перевод земель и отказ или изъятие в будущем.`,
      law: "ст. 23 ГрК РФ; ст. 56.3 ЗК РФ",
      source: "генплан",
    });
  }
  if (plan.has("planned")) {
    memo.check.push({
      text: "По участку проходит планируемый объект (дорога, ЛЭП, трубопровод): документы терпланирования — основание изъятия для государственных или муниципальных нужд; вложения в эту часть участка рискованны.",
      law: "ч. 1 ст. 56.3 ЗК РФ",
      source: "генплан",
    });
  }
  if (plan.has("nodata")) {
    memo.check.push({
      text: "Генплана на участок в НСПД нет — спросить администрацию, есть ли утверждённый генплан и какая зона на участке.",
      law: "ст. 23 ГрК РФ",
      source: "генплан",
    });
  }

  // Что можно по умолчанию — если проверки сделаны и ничего не нашлось
  const restrictionsClean = p.restrictionsCheckedAt && zones.size === 0;
  const waterClean = p.survey.water.length > 0 && p.survey.water.every((w) => waterStrips(w).touches === false);
  if (restrictionsClean) {
    memo.allowed.push({
      text: "ЗОУИТ, ООПТ и лесничеств по ЕГРН на участке нет — сельхозработы без особых ограничений.",
      law: "ст. 105–106 ЗК РФ",
      source: "ЕГРН",
    });
  }
  if (waterClean) {
    memo.allowed.push({
      text: "Водоохранные и прибрежные полосы от ближайшей воды до участка не доходят.",
      law: "ст. 65 ВК РФ",
      source: "закон",
    });
  }
  return memo;
}

export const memoSections = [
  { key: "forbidden", title: "Нельзя", tone: "bad" },
  { key: "conditional", title: "Можно при условии", tone: "warn" },
  { key: "check", title: "Уточнить", tone: "warn" },
  { key: "allowed", title: "Можно", tone: "ok" },
] as const;

export function memoText(cadastralNumber: string, memo: Memo) {
  const lines = [`Памятка по участку ${cadastralNumber}`];
  for (const s of memoSections) {
    if (!memo[s.key].length) continue;
    lines.push("", `${s.title}:`);
    for (const i of memo[s.key]) lines.push(`— ${i.where ? `${i.where}: ` : ""}${i.text} (${i.law}; источник: ${i.source})`);
  }
  lines.push("", "Нормы — по действующим редакциям; перед важным решением сверьтесь с текстом закона.");
  return lines.join("\n");
}
